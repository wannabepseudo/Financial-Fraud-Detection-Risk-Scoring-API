"""
Analytics & Transaction Stream Routes
"""

from fastapi import APIRouter
import os
from typing import Dict, Any, List
from app.db import get_analytics_summary, get_recent_transactions
from app.config import STATIC_DIR

router = APIRouter(prefix="/analytics", tags=["Analytics & Stream"])


@router.get("/stats", summary="Get Aggregated Financial Transaction Statistics")
async def get_stats():
    """
    Returns high-level statistics across the 45,000+ transaction database.
    """
    return get_analytics_summary()


@router.get("/recent", summary="Get Recent Transactions Stream")
async def get_recent():
    """
    Returns recent transactions with metadata for the live stream monitor.
    """
    return get_recent_transactions(limit=25)


